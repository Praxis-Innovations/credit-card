/**
 * Builds the static catalog snapshot the marketing site (apps/web) renders its
 * category pages from. The site never calls the API; it ships this snapshot.
 *
 * Source of truth: apps/api/src/domain/cards.ts and valuations.ts. Write the
 * file with `pnpm snapshot:catalog`; apps/web tests fail when the committed
 * snapshot no longer matches what this builder produces.
 */
import { CARDS } from "../apps/api/src/domain/cards.ts";
import { DEFAULT_POINT_VALUATIONS } from "../apps/api/src/domain/valuations.ts";

/** Categories with a marketing page, plus the fallback rate they inherit. */
export const SNAPSHOT_CATEGORIES = ["gas", "groceries", "dining"] as const;
const SNAPSHOT_RATE_CATEGORIES: readonly string[] = [
  ...SNAPSHOT_CATEGORIES,
  "other",
];

export const SNAPSHOT_PATH = "apps/web/src/data/catalog-snapshot.json";

export function buildCatalogSnapshot() {
  return {
    $comment:
      "Generated by scripts/export-catalog-snapshot.ts from apps/api/src/domain. Do not edit by hand; run `pnpm snapshot:catalog`.",
    sources: [
      "apps/api/src/domain/cards.ts",
      "apps/api/src/domain/valuations.ts",
    ],
    categories: [...SNAPSHOT_CATEGORIES],
    valuations: { ...DEFAULT_POINT_VALUATIONS },
    cards: CARDS.map((card) => ({
      id: card.id,
      issuer: card.issuer,
      name: card.name,
      annualFee: card.annualFee,
      pointCurrency: card.pointCurrency,
      ...(card.network ? { network: card.network } : {}),
      lastVerified: card.lastVerified,
      rewardCategories: card.rewardCategories
        .filter((r) => SNAPSHOT_RATE_CATEGORIES.includes(r.category))
        .map((r) => ({
          category: r.category,
          earnRate: r.earnRate,
          ...(r.capMonthly !== undefined ? { capMonthly: r.capMonthly } : {}),
          ...(r.capAnnual !== undefined ? { capAnnual: r.capAnnual } : {}),
        })),
    })),
  };
}

export function serializeCatalogSnapshot(): string {
  return `${JSON.stringify(buildCatalogSnapshot(), null, 2)}\n`;
}
